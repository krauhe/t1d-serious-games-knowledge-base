/**
 * Restore the long-form physiological reference without importing game code.
 *
 * Dette er en strukturel overførsel, ikke et litteraturreview. Faglige rettelser
 * foretages kun i BG-SCIENCE.md. Generatoren fjerner implementerings-footers og
 * reparerer interne henvisninger, men ændrer ikke videnskabelige udsagn.
 * --write --auto bruges af build-hooket; --check kontrollerer det gemte snapshot.
 * Lokale ændringer i genererede kapitler blokerer overskrivning.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceArgument = process.argv.indexOf('--source');
if (sourceArgument >= 0 && (!process.argv[sourceArgument + 1] || process.argv[sourceArgument + 1].startsWith('--'))) throw new Error('--source requires a file path');
const explicitSource = sourceArgument >= 0 ? process.argv[sourceArgument + 1] : process.env.T1D_BG_SCIENCE;
const sourcePath = path.resolve(explicitSource || path.join(root, '../Diabetes Simulator - Virtuel udforskning af din virkelighed/docs/BG-SCIENCE.md'));
const sourceRoot = path.dirname(path.dirname(sourcePath));
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const textHash = value => hash((Buffer.isBuffer(value) ? value.toString('utf8') : value).replaceAll('\r\n','\n'));
const output = 'knowledge/physiology/reference';
const audit = 'docs/reviews/2026-09-16_physiology-restoration';
const manifestPath = path.join(root, audit, 'coverage.json');
const previous = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : null;
const write = process.argv.includes('--write');
const check = process.argv.includes('--check');
const auto = process.argv.includes('--auto');
const generatorHash = textHash(fs.readFileSync(fileURLToPath(import.meta.url)));
function validateSnapshot() {
  if (!previous?.sections?.length) throw new Error('No committed physiology snapshot is available');
  for (const record of previous.sections) {
    const destination = path.resolve(root, record.output);
    if (!destination.startsWith(path.resolve(root, output) + path.sep)) throw new Error('Unexpected physiology output path in manifest');
    if (!fs.existsSync(destination)) throw new Error(`Missing physiology snapshot: ${record.output}`);
    const currentHash=previous.hash_normalization==='UTF-8 text with LF line endings' ? textHash(fs.readFileSync(destination)) : hash(fs.readFileSync(destination));
    if (currentHash !== record.output_sha256) throw new Error(`Generated physiology chapter was edited: ${record.output}. Preserve that change in canonical BG-SCIENCE.md before synchronising.`);
  }
}
if (!fs.existsSync(sourcePath)) {
  if (explicitSource || !auto) throw new Error(`Physiology source not found: ${sourcePath}`);
  validateSnapshot();
  if (previous.generator_sha256 !== generatorHash) throw new Error('Offline physiology snapshot was generated by a different importer; refresh it with the canonical source available before publication');
  console.log('Physiology source is unavailable; verified committed snapshot retained (offline/CI).');
  process.exit(0);
}
const sourceBytes = fs.readFileSync(sourcePath);
const source = sourceBytes.toString('utf8').replaceAll('\r\n', '\n');
const sourceHash = textHash(sourceBytes);
const sourceVersion = source.match(/doc-version: ([^ ]+)/)?.[1];
if (!sourceVersion) throw new Error('Canonical physiology source needs a doc-version marker');
if (previous) validateSnapshot();
if (previous?.source_sha256 === sourceHash && previous?.generator_sha256 === generatorHash) {
  console.log('Physiology source and generated chapters unchanged; snapshot verified.');
  process.exit(0);
}
if (check) throw new Error('Physiology snapshot is stale; run the authorised sync before building');
const sectionPattern = /<a name="([^"]+)"><\/a>\n## (\d+b?)\. ([^\n]+)/g;
const sections = [...source.matchAll(sectionPattern)].map((match, index) => ({
  id: match[2], anchor: match[1], title: match[3], start: match.index,
  bodyStart: match.index + match[0].length, index,
  source: `${output}/${match[2].padStart(2, '0')}-${match[1]}.qmd`
}));
if (sections.length < 30) throw new Error(`Expected at least 30 topical sections, found ${sections.length}; inspect source structure before importing`);
if (new Set(sections.map(section => section.id)).size !== sections.length || new Set(sections.map(section => section.anchor)).size !== sections.length) throw new Error('Duplicate physiology section number or anchor');
if (sections.some(section => !/^[a-z0-9][a-z0-9-]*$/i.test(section.anchor))) throw new Error('Unsafe physiology anchor/file name');
if (new Set(sections.map(section => section.source)).size !== sections.length) throw new Error('Duplicate physiology output path');
const outputPaths=new Set(sections.map(section=>section.source));
const obsolete=(previous?.sections||[]).filter(section=>!outputPaths.has(section.output));
if (obsolete.length) throw new Error(`Previously generated chapters no longer mapped; review rather than silently delete: ${obsolete.map(section=>section.output).join(', ')}`);
const anchors = new Map();
for (const section of sections) {
  section.raw = source.slice(section.bodyStart, sections[section.index + 1]?.start ?? source.length);
  anchors.set(section.anchor, section);
  for (const match of section.raw.matchAll(/<a name="([^"]+)"><\/a>/g)) anchors.set(match[1], section);
}
const aliases = {dawn:'dawn-phenomenon', 'hypoglycemia-haaf':'counterregulatory-hormones', exercise:'aerobic-exercise', temperature:'temperature-climate'};
for (const [alias, target] of Object.entries(aliases)) anchors.set(alias, anchors.get(target));
let sourceGit = null;
try {
  sourceGit = {commit:execFileSync('git',['rev-parse','HEAD'],{cwd:sourceRoot,encoding:'utf8'}).trim(), source_dirty:!!execFileSync('git',['status','--porcelain','--',path.relative(sourceRoot,sourcePath)],{cwd:sourceRoot,encoding:'utf8'}).trim()};
} catch { /* Ikke alle eksplicit valgte kilder ligger i et Git-repository. */ }
const ledger = {source:'T1D Simulator/docs/BG-SCIENCE.md', source_version:sourceVersion, source_sha256:sourceHash, hash_normalization:'UTF-8 text with LF line endings', generator_sha256:generatorHash, source_git_at_generation:sourceGit, mode:'Structural transfer from canonical source; no KB-specific scientific corrections; not independent source appraisal', sections:[], omissions:[]};
const manifests = [];
const pendingWrites = new Map();
function save(relative, body) {
  pendingWrites.set(relative,body);
}
function wordCount(text) { return (text.replace(/\]\([^)]*\)/g, ']').match(/[\p{L}\p{N}]+/gu) || []).length; }
for (const section of sections) {
  let body = section.raw.split('\n').filter((line, index) => {
    const omit = /^\*Implementation:|^>.*\*\*Implementation:|^# Part \d+:|^\*\*(?:Active in simulator|Partially modeled|Not implemented)\*\*/u.test(line);
    if (omit) ledger.omissions.push({section:section.id, reason: /^# Part/.test(line) ? 'Part divider replaced by module navigation' : 'Affiliated simulator implementation footer', original:line});
    return !omit;
  }).join('\n');
  // Link original section labels across their new files; aliases repair four
  // pre-existing broken fragment names rather than preserving dead links.
  body = body.replace(/\]\(#([^)]*)\)/g, (whole, anchor) => {
    const canonical = aliases[anchor] || anchor;
    const destination = anchors.get(anchor);
    if (!destination) throw new Error(`Unresolved source anchor: ${section.id} -> ${anchor}`);
    return `](${destination === section ? '' : path.basename(destination.source)}#${canonical})`;
  }).replace(/<a name="([^"]+)"><\/a>/g, '<a id="$1"></a>');
  // Plain section references remain meaningful after separating the chapters.
  // Do not rewrite references already inside Markdown links.
  body = body.replace(/(?<!\[)§(\d+b?)(?![\d\]])/g, (whole, id, offset, text) => {
    if (text.slice(Math.max(0, text.lastIndexOf('\n', offset)), offset).lastIndexOf('[') > text.slice(Math.max(0, text.lastIndexOf('\n', offset)), offset).lastIndexOf(']')) return whole;
    const destination = sections.find(candidate => candidate.id === id);
    return destination ? `[§${id}](${path.basename(destination.source)})` : whole;
  });
  body = body.replace(/\n(?:\s*---\s*\n)+$/g, '\n').trim();
  if (/MODEL-IMPLEMENTATION|Implementation:|this simulator|T1D Simulator|TODO #/.test(body)) throw new Error(`Implementation leakage in section ${section.id}`);
  const preamble = `---\ntitle: ${JSON.stringify(section.title.replaceAll(' -- ', ' — '))}\ndescription: "Detailed physiological reference: mechanisms, quantitative evidence and limitations."\nsource-version: ${JSON.stringify(sourceVersion)}\nstatus: "Canonical physiology reference; source appraisal varies by claim"\n---\n\n<!-- Generated from BG-SCIENCE.md; make scientific changes in the canonical source. -->\n\n[Physiology contents](../index.qmd)\n\n> **Reference status:** source version ${sourceVersion}. Automatic transfer is not a new literature search or independent verification of every claim. Quantities describe the cited populations and protocols, not personal treatment parameters.\n\n<a id="${section.anchor}"></a>\n\n`;
  const result = preamble + body + '\n';
  save(section.source, result);
  ledger.sections.push({id:section.id, title:section.title, source_line:source.slice(0, section.start).split('\n').length, output:section.source, source_words:wordCount(section.raw), restored_words:wordCount(body), output_sha256:textHash(result), coverage:'Transferred without scientific rewriting; source appraisal incomplete'});
  manifests.push({title:section.title.replaceAll(' -- ', ' — '), source:section.source});
}
const referenceRecords = new Map();
for (const section of sections) {
  const body = pendingWrites.get(section.source);
  for (const match of body.matchAll(/\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)/g)) {
    const url = match[2];
    if (!referenceRecords.has(url)) referenceRecords.set(url, {url, labels:[], used_in:[], identity_status:'Inherited citation; identity and claim support not fully revalidated', acquisition_status:'Unreconciled'});
    const record = referenceRecords.get(url);
    if (!record.labels.includes(match[1])) record.labels.push(match[1]);
    if (!record.used_in.includes(section.source)) record.used_in.push(section.source);
  }
}
save(`${audit}/coverage.json`, JSON.stringify(ledger, null, 2) + '\n');
save(`${audit}/navigation.json`, JSON.stringify(manifests, null, 2) + '\n');
save(`${audit}/inherited-citations.json`, JSON.stringify([...referenceRecords.values()], null, 2) + '\n');
// Alle kapitler er nu analyseret. Kontroller også nye, endnu ikke registrerede
// destinationsfiler, så en brugerfil aldrig overtages uden en eksplicit beslutning.
for (const section of sections) {
  const destination=path.join(root,section.source);
  if (fs.existsSync(destination) && !previous?.sections?.some(row=>row.output===section.source) && fs.readFileSync(destination,'utf8')!==pendingWrites.get(section.source)) throw new Error(`Unmanaged existing physiology file: ${section.source}`);
}
if (write) {
  // Klargør alle ændrede filer før omdøbning. Manifestet skrives sidst; en
  // afbrudt diskoperation kan derfor ikke udgive et falsk gyldigt snapshot.
  const staged=[];
  for (const [relative,body] of pendingWrites) {
    const destination=path.join(root,relative);
    if (fs.existsSync(destination) && fs.readFileSync(destination,'utf8')===body) continue;
    fs.mkdirSync(path.dirname(destination),{recursive:true});
    const temporary=`${destination}.sync-${process.pid}.tmp`;
    fs.writeFileSync(temporary,body,'utf8');
    staged.push({destination,temporary});
  }
  staged.sort((left,right)=>Number(left.destination===manifestPath)-Number(right.destination===manifestPath));
  for (const file of staged) {
    for (let attempt=0;;attempt++) {
      try { fs.renameSync(file.temporary,file.destination); break; }
      catch(error) {
        // Dropbox/antivirus kan holde en netop skrevet fil kortvarigt åben.
        // Genforsøg er begrænset; vi sletter aldrig målet som workaround.
        if (!['EPERM','EBUSY'].includes(error.code) || attempt>=5) throw error;
        Atomics.wait(new Int32Array(new SharedArrayBuffer(4)),0,0,50*(attempt+1));
      }
    }
  }
}
console.log(JSON.stringify({write, sections:sections.length, words:ledger.sections.reduce((sum,row)=>sum+row.restored_words,0), omissions:ledger.omissions.length, inherited_external_urls:referenceRecords.size, source_sha256:ledger.source_sha256},null,2));
